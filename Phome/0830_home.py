# 9번. 문자열 회원 데이터 처리
# ------------------------------------------------------------
# 회원 정보가 다음과 같은 하나의 문자열로 들어왔습니다.
#
# data = "1001,영희,35,160.5"
# 쉼표(,)를 기준으로 분리하세요.
#
# 그리고 다음처럼 출력하세요.
#
# 회원번호 : 1001
# 이름 : 영희
# 나이 : 35
# 키 : 160.5
#
# 추가 조건:
#
# 나이는 int 타입으로 변환하세요.
# 키는 float 타입으로 변환하세요.
#
# 마지막으로 다음도 출력하세요.
# 나이 자료형 : <class 'int'>
# 키 자료형 : <class 'float'>
#
# 아래에 코드를 작성하세요.
data = "1001,영희,35,160.5"
data1 = data.split(",")
print(f"회원번호 : {data1[0]}")
print(f"이름 : {data1[1]}")
print(f"나이 : {int(data1[2])}")
print(f"키 : {float(data1[3])}")





